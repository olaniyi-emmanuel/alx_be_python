#Subtraction of 10 and 5 is 5
#Multiplication of 10 and 5 is 50

number1 = 5
number2 = 10

# Addition 
def addition(number1, number2):
    return print(f"Addition of {number1} and {number2} is {number1 + number2}")
addition(number1, number2)

def subtraction(number1, number2):
    return print(f"Subtraction of {number1} and {number2} is {number1 - number2}")
subtraction(number1, number2)

def multiplication(number1, number2):
    return print(f"Multiplication of {number1} and {number2} is {number1 * number2}")
multiplication(number1, number2)
